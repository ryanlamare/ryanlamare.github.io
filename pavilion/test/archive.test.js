section('Deriving a result by replay (result.js)');

{
  const room = playedRoom();
  room.ended = { ending: 'natural' };
  const r = deriveResult(room);

  eq(r.ending, 'natural', 'a natural end stays natural');
  same(r.scores, room.final.result.scores, 'the replay reaches the same scores as playing it did');
  eq(r.winner, room.final.result.winner, 'and names the same winner');
  eq(r.plies, room.moves.length, 'the record knows how long the game was');
  ok(/^[0-9a-f]{8}$/.test(r.hash), 'and carries the final state hash as its own fingerprint');
  eq(r.points.reduce((a, b) => a + b, 0), r.winner >= 0 ? 4 : 4, 'league points total 4 over a two-player game');

  // The whole point: what the client *said* never reaches the record.
  const lying = deriveResult({ ...room }, { ending: 'natural', result: { scores: [999, 0], winner: 0 } });
  same(lying.scores, r.scores, "a client's claimed scores are ignored — the server replays instead");
}

{
  // A claim the move list does not support is not a result. It voids, with the
  // reason kept, because a game that cannot be reproduced is a bug report.
  const room = playedRoom({ stopAfter: 12 });
  const r = deriveResult(room, { ending: 'natural' });
  eq(r.ending, 'void', 'claiming a natural end the moves never reach voids the game');
  ok(/does not reach/.test(r.reason), 'and says why');
  eq(r.points, null, 'a void game scores nothing, not even the point for playing');
}

{
  const room = playedRoom();
  room.moves[3].move = { source: { type: 'source', index: 0 }, kind: 9, dest: { type: 'floor' } };
  const r = deriveResult(room, { ending: 'natural' });
  eq(r.ending, 'void', 'a move list that no longer replays voids rather than throwing');
  ok(/replay failed/.test(r.reason), 'and says the replay failed');
}

{
  // §11: timeout loses like chess. The board is mid-game, so the scores are the
  // running ones and no §8 bonus has been applied.
  const room = playedRoom({ stopAfter: 30 });
  const r = deriveResult(room, { ending: 'timeout', flagged: 0 });
  eq(r.ending, 'timeout', 'a timeout is recorded as a timeout');
  eq(r.winner, 1, 'the seat that did not flag wins');
  eq(r.flagged, 0, 'and the record says who ran out');
  same(r.points, [1, 3], 'league points follow the ranking, not the score');
  const mid = replay(room.seed, room.players, room.moves.map((m) => m.move));
  same(r.scores, mid.boards.map((b) => b.score), 'the scores are the running board scores, no end bonuses');

  const late = deriveResult(playedRoom(), { ending: 'timeout', flagged: 0 });
  eq(late.ending, 'void', 'a timeout claimed after the game had already finished voids');
}

