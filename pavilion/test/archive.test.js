let passed = 0;
let failed = 0;

function ok(cond, msg) {
  if (cond) passed++;
  else {
    failed++;
    console.error('  FAIL: ' + msg);
  }
}

function eq(got, want, msg) {
  ok(got === want, `${msg} (got ${JSON.stringify(got)}, want ${JSON.stringify(want)})`);
}

function same(got, want, msg) {
  eq(JSON.stringify(got), JSON.stringify(want), msg);
}

function section(title) {
  console.log('— ' + title);
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

function waitFor(relay, type, predicate = () => true, ms = 6000) {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(`timed out waiting for "${type}"`)), ms);
    const CB = (payload) => {
      if (!predicate(payload)) return;
      clearTimeout(timer);
      relay.listeners.get(type).delete(CB);
      resolve(payload);
    };
    relay.on(type, CB);
  });
}

// A complete game, played deterministically, in the shape a finished room has.
// Nothing here is a fixture file: the moves are generated by the engine, so a
// rules change that breaks the archive breaks this suite too.
function playedRoom({ seed = 'archive-test', players = 2, seats = null, stopAfter = null } = {}) {
  let s = newGame(seed, players);
  const moves = [];
  let guard = 0;
  while (!s.over && guard++ < 600) {
    const options = legalMoves(s);
    const move = options[(moves.length * 7 + s.seatToMove) % options.length];
    moves.push({ seat: s.seatToMove, move: { ...move, t: moves.length * 1000 }, at: 1_700_000_000_000 + moves.length });
    s = apply(s, moves[moves.length - 1].move);
    if (stopAfter && moves.length >= stopAfter) break;
  }
  return {
    code: 'FERRIS-NORWAY',
    seed,
    players,
    clockMs: 300000,
    mode: 'league',
    splashHistory: true,
    startedAt: 1_700_000_000_000,
    seats:
      seats ||
      Array.from({ length: players }, (_, i) => ({
        seat: i,
        name: ['Sam', 'Alex', 'Jordan', 'Riley'][i],
        pid: ['sam', 'alex', 'jordan', 'riley'][i],
        device: i ? 'phone' : 'laptop',
        connected: true,
        id: `tok-${i}`,
      })),
    moves,
    ended: null,
    final: s,
  };
}

