// Pavilion — the archive, headless (build step 5).
//
//   node pavilion/test/archive.test.js
//
// Three layers, in order of how much they can break:
//
//   1. `result.js` — replay a finished game and derive the winner. This is the
//      file that makes an archived result unforgeable, so it is tested against
//      real move lists and against claims that contradict them.
//   2. `archive.js` — term, roster, classification and storage, over the same
//      MemoryStore the dev relay uses.
//   3. The whole thing over real WebSockets: set a term and a roster through
//      the admin API, play a complete game between two rostered clients, and
//      check that the record wrote itself with nobody reporting anything.
//
// No dependencies and no browser, like every other suite here.

