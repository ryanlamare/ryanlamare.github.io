section('Writing, reading and amending a record');

{
  const a = new Archive(new MemoryStore());
  await a.setConfig({ term: '2026-fall' });
  await a.setRoster(['Sam', 'Alex', { name: 'Ryan', instructor: true }]);

  const room = playedRoom();
  room.ended = { ending: 'natural' };
  const receipt = await a.record(room, 1_700_000_100_000);
  eq(receipt.recorded, true, 'a finished game records itself');
  eq(receipt.mode, 'league', 'as a league game');

  const rec = await a.game(receipt.id);
  eq(rec.v, 1, 'the record carries the engine version it was played under');
  eq(rec.term, '2026-fall', 'and its term, from day one — the Record Book accrues across years');
  same(rec.seats, ['sam', 'alex'], 'seats are roster ids in join order');
  same(rec.names, ['Sam', 'Alex'], 'with the names kept so a record reads on its own');
  same(rec.device, ['laptop', 'phone'], 'and the device per seat, for the clock-fairness question');
  eq(rec.moves.length, room.moves.length, 'the whole move list is stored, not just the result');
  eq(rec.seed, room.seed, 'so seed + moves replays the game exactly');
  same(replay(rec.seed, rec.players, rec.moves.map((m) => m.move)).result.scores, rec.result.scores,
    'and the stored record replays back to the stored scores');

  const sum = summarize(rec);
  eq(sum.moves, undefined, 'a summary drops the move list');
  eq(sum.plies, rec.moves.length, 'but keeps how long the game was');

  const listed = await a.games('2026-fall');
  eq(listed.length, 1, 'the term lists its games');
  eq(listed[0].moves, undefined, 'as summaries, so a league table never loads a move list');
  same(await a.terms(), ['2026-fall'], 'and the archive knows which terms exist');

  // A second game in the same room — a rematch — is a different game.
  const second = playedRoom({ seed: 'archive-test-2' });
  second.startedAt = room.startedAt + 60000;
  second.ended = { ending: 'natural' };
  const r2 = await a.record(second, 1_700_000_200_000);
  ok(r2.id !== receipt.id, 'a rematch in the same room archives as its own game');
  eq((await a.games('2026-fall')).length, 2, 'both are in the term');
  eq((await a.games('2026-fall'))[0].id, r2.id, 'newest first');

  // --- the two instructor overrides ---------------------------------------
  eq((await a.setMode(receipt.id, 'cup')).mode, 'cup', 'a game can be retagged as a cup game after the fact');
  eq((await a.setMode(receipt.id, 'nonsense')).mode, 'cup', 'and nonsense leaves it alone');

  const voided = await a.setEnding(receipt.id, 'void', 'the wifi, not the player');
  eq(voided.result.ending, 'void', 'a game can be voided when the wifi was the problem');
  eq(voided.result.points, null, 'a voided game stops scoring');
  eq(voided.result.reason, 'the wifi, not the player', 'and says why');

  const restored = await a.setEnding(receipt.id, 'natural');
  same(restored.result.scores, rec.result.scores, 'un-voiding re-derives from the move list rather than trusting old numbers');
  eq((await a.game(receipt.id)).moves.length, rec.moves.length, 'and never touches the moves');

  // The trap: a voided *timeout* restored as "natural" would replay to a game
  // the moves never finish, and void itself straight back again.
  const flagged = playedRoom({ seed: 'archive-test-3', stopAfter: 30 });
  flagged.startedAt = room.startedAt + 120000;
  const t = await a.record({ ...flagged, ended: { ending: 'timeout', flagged: 1 } }, 1_700_000_300_000);
  eq((await a.game(t.id)).result.winner, 0, 'a timeout records the seat that did not flag as the winner');
  await a.setEnding(t.id, 'void', 'the wifi');
  const back = await a.setEnding(t.id, 'natural');
  eq(back.result.ending, 'timeout', 'restoring a voided timeout puts back a timeout, not a natural end');
  eq(back.result.winner, 0, 'with the same winner it had before');

  eq(await a.setMode('no-such-game', 'cup'), null, 'amending a game that is not there returns nothing');
}

