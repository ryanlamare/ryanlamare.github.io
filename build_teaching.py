def crumbs(trail):
    """trail is [(label, href or None), ...]; the last item is the current page.

    The hub is its own only crumb, so it gets none — the h1 already says it.
    """
    if len(trail) < 2:
        return ""
    out = []
    for label, href in trail:
        out.append(f'<a href="{href}">{label}</a>' if href else f"<span>{label}</span>")
    return '<i>&rsaquo;</i>'.join(out)


