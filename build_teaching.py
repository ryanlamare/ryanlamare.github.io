# ---------------------------------------------------------------- components
def course_row(aff, c):
    """One course: a link into its decks, or out to a course guide if it has none."""
    bits = [x for x in (c.get("level"), c.get("term")) if x]
    if not c.get("dir") and c.get("external"):
        bits.append(c.get("external_label", "Course guide"))
    meta = " &middot; ".join(bits)

    inner = (
        f'        <div class="code">{c["code"]}</div>\n'
        f'        <div>\n'
        f'          <h3>{c["title"]}</h3>\n'
        + (f'          <div class="meta">{meta}</div>\n' if meta else "")
        + f'          <p>{c["blurb"]}</p>\n'
        f'        </div>\n'
        f'        <div class="go" aria-hidden="true">&rsaquo;</div>\n'
    )
    if c.get("dir"):
        open_tag = f'<a class="crs" href="/teaching/{c["dir"]}/">'
    elif c.get("external"):
        open_tag = f'<a class="crs" href="{c["external"]}" target="_blank" rel="noopener">'
    else:
        return f'        <div class="crs">\n{inner}        </div>'
    return f"        {open_tag}\n{inner}        </a>"


def aff_block(aff, heading=True):
    """An institution and its courses.

    On the affiliation's own page the masthead has already named it, so the
    heading is dropped rather than printed twice.
    """
    rows = "\n".join(course_row(aff, c) for c in aff["courses"])
    head = (
        f'      <div class="aff-head">\n'
        f'        <h2><a href="/teaching/{aff["slug"]}/">{aff["name"]}</a></h2>\n'
        f'        <div class="unit">{aff["unit"]}</div>\n'
        f'      </div>\n'
        if heading
        else ""
    )
    return (
        f'    <section class="aff{"" if heading else " bare"}">\n{head}'
        f'      <div class="aff-list">\n{rows}\n      </div>\n'
        f'    </section>'
    )


def week_block(n, decks):
    rows = "\n".join(
        f'        <a class="deck" href="{href}">'
        f'<span class="k">{label}</span>'
        f'<span class="t">{topic}</span>'
        f'<span class="go" aria-hidden="true">&rsaquo;</span></a>'
        for label, href, topic in decks
    )
    return (
        f'      <div class="wk">\n'
        f'        <div><div class="wklab">Week</div><div class="wknum">{n}</div></div>\n'
        f'        <div>\n{rows}\n        </div>\n'
        f'      </div>'
    )


# ------------------------------------------------------------------ the pages
def build_hub():
    return page(
        title="Teaching — J. Ryan Lamare",
        desc="Lecture slides and live sessions from J. Ryan Lamare's courses.",
        trail=[("Teaching", None)],
        kick="Course materials",
        h1="Teaching",
        sub=(
            "Lecture slides and live sessions, as they were taught. "
            "Everything here runs in a browser &mdash; nothing to download."
        ),
        body="\n\n".join(aff_block(a) for a in D.AFFILIATIONS),
    )


def build_affiliation(aff):
    return page(
        title=f'{aff["short"]} teaching — J. Ryan Lamare',
        desc=f'Courses taught by J. Ryan Lamare at {aff["name"]}.',
        trail=[("Teaching", "/teaching/"), (aff["short"], None)],
        kick=aff["unit"],
        h1=aff["name"],
        h1_class=' class="sm"',
        sub=None,
        body=aff_block(aff, heading=False),
    )


def build_course(aff, c):
    ws = weeks(c)
    blocks = "\n".join(week_block(n, decks) for n, decks in ws)
    note = (
        '      <p class="note">Slides open in the browser and advance with the arrow keys, '
        "space, or a tap. Every deck carries a full text version for screen readers.</p>"
    )
    body = f'    <section class="weeks">\n{blocks}\n{note}\n    </section>'
    return page(
        title=f'{c["code"]} — {c["title"]} — J. Ryan Lamare',
        desc=f'{c["code"]}, {c["title"]}: lecture slides and live sessions.',
        trail=[("Teaching", "/teaching/"), (aff["short"], f'/teaching/{aff["slug"]}/'),
               (c["code"], None)],
        kick=f'{aff["short"]} &middot; {c["code"]}',
        h1=c["title"],
        sub=c["blurb"],
        body=body,
    )


# ----------------------------------------------------------------------- main
def main():
    check = "--check" in sys.argv

    targets = [(os.path.join(ROOT, "index.html"), build_hub())]
    for aff in D.AFFILIATIONS:
        targets.append(
            (os.path.join(ROOT, aff["slug"], "index.html"), build_affiliation(aff))
        )
        for c in courses_with_decks(aff):
            targets.append(
                (os.path.join(ROOT, c["dir"], "index.html"), build_course(aff, c))
            )

    changed = []
    for path, new in targets:
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
        if old != new:
            changed.append(os.path.relpath(path, HERE))
            if not check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w", encoding="utf-8").write(new)

    decks = sum(
        len(d) for a in D.AFFILIATIONS for c in courses_with_decks(a) for _, d in weeks(c)
    )
    print(f"{decks} decks across {len(targets)} index pages")
    if check:
        print("CHANGED:" if changed else "up to date:", changed or "no differences")
        sys.exit(1 if changed else 0)
    print("wrote:", ", ".join(changed) if changed else "nothing (already up to date)")


if __name__ == "__main__":
    main()
