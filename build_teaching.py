"""Build the teaching hub — the index pages that make the decks browsable.

    python3 build_teaching.py
    python3 build_teaching.py --check     # exit 1 if anything is out of date

Writes an index.html for the hub, for each affiliation, and for each course
that has a directory of decks:

    teaching/index.html
    teaching/<affiliation>/index.html
    teaching/<affiliation>/<course>/index.html

Framing (which affiliations, which courses, how they read) comes from
teaching_data.py. Weeks are not listed anywhere: this script walks the course
directory, finds week<N>/lecture/ and week<N>/live/, and takes each deck's
name from its own <title>. Add a week folder and it appears here; there is no
second place to update.

Only lecture and live-session decks are indexed. Games, quizzes, brackets and
shortlist rounds are reachable from inside a live deck during a session and
are deliberately not listed.

Never hand-edit the generated index.html files — this script overwrites them.
The decks themselves are hand-written and are never touched.
"""
import os
import re
import sys

import teaching_data as D

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "teaching")

GENERATED = "<!-- GENERATED by build_teaching.py from teaching_data.py — do not edit by hand. -->"

# The two deck kinds an index lists, in the order they appear in a week.
KINDS = [("lecture", "Lecture"), ("live", "Live session")]

TITLE = re.compile(r"<title>(.*?)</title>", re.S | re.I)
# "LER 565 · Week 4 — Coordination Games in HR"
# "LER 565 · Week 4 Live Session — Coordination Games between HR and Management"
DECK = re.compile(r"·\s*Week\s*\d+(?:\s+Live Session)?\s*[—–-]\s*(?P<topic>.+?)\s*$", re.S)
WEEKDIR = re.compile(r"^week(\d+)$")


# ------------------------------------------------------------------ the walk
def deck_topic(path):
    """The deck's own name for itself, from its <title>.

    Falls back to the whole title if it does not follow the house format, so a
    differently-named deck still lists rather than silently vanishing.
    """
    m = TITLE.search(open(path, encoding="utf-8").read(4096))
    if not m:
        return None
    title = " ".join(m.group(1).split())
    m = DECK.search(title)
    return m.group("topic") if m else title


def weeks(course):
    """[(n, [(kind_label, href, topic), ...]), ...] for a course, in week order."""
    cdir = os.path.join(ROOT, course["dir"])
    found = []
    for name in sorted(os.listdir(cdir)):
        m = WEEKDIR.match(name)
        if not m or not os.path.isdir(os.path.join(cdir, name)):
            continue
        decks = []
        for kind, label in KINDS:
            path = os.path.join(cdir, name, kind, "index.html")
            if os.path.exists(path):
                topic = deck_topic(path)
                if topic:
                    decks.append((label, f"{name}/{kind}/", topic))
        if decks:
            found.append((int(m.group(1)), decks))
    return sorted(found)


def courses_with_decks(aff):
    return [c for c in aff["courses"] if c.get("dir")]


